create or replace function public.admin_grant_shop_item(p_user_id uuid, p_item_id text)
returns text
language plpgsql
security definer
set search_path = ''
as $$
declare v_admin uuid := auth.uid();
begin
  if v_admin is null or not exists (select 1 from public.quest_admins a where a.user_id = v_admin) then
    raise exception 'administrator access required' using errcode = '42501';
  end if;
  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended('shop:' || p_user_id::text, 0));
  if not exists (select 1 from public.guild_profiles p where p.user_id = p_user_id) then
    raise exception 'unknown user' using errcode = '22023';
  end if;
  if not exists (select 1 from public.shop_items i where i.id = p_item_id and i.active) then
    raise exception 'shop item unavailable' using errcode = '22023';
  end if;
  if exists (select 1 from public.shop_purchases p where p.user_id = p_user_id and p.item_id = p_item_id)
     or exists (select 1 from public.shop_item_grants g where g.user_id = p_user_id and g.item_id = p_item_id) then
    return 'already_owned';
  end if;
  insert into public.shop_item_grants (user_id, item_id, granted_by) values (p_user_id, p_item_id, v_admin);
  return 'granted';
end;
$$;

