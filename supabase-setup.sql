create or replace function public.use_shop_item(p_item_id text)
returns text
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := auth.uid();
  v_available integer;
begin
  if v_user_id is null then raise exception 'authentication required' using errcode = '28000'; end if;
  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended('shop:' || v_user_id::text, 0));
  select coalesce((select p.quantity from public.shop_purchases p where p.user_id = v_user_id and p.item_id = p_item_id), 0)
       + coalesce((select count(*)::integer from public.shop_item_grants g where g.user_id = v_user_id and g.item_id = p_item_id), 0)
       - coalesce((select count(*)::integer from public.shop_item_uses u where u.user_id = v_user_id and u.item_id = p_item_id and u.restored_at is null), 0)
    into v_available;
  if v_available < 1 then
    return 'not_owned';
  end if;
  insert into public.shop_item_uses (user_id, item_id) values (v_user_id, p_item_id);
  return 'used';
end;
$$;

drop function if exists public.purchase_shop_item(text);
drop function if exists public.purchase_shop_item(text, integer);
create function public.purchase_shop_item(p_item_id text, p_quantity integer)
returns text
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := auth.uid();
  v_price integer;
  v_total bigint;
  v_balance bigint;
begin
  if v_user_id is null then
    raise exception 'authentication required' using errcode = '28000';
  end if;
  if p_quantity is null or p_quantity < 1 then
    raise exception 'quantity must be a positive integer' using errcode = '22023';
  end if;

  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended('shop:' || v_user_id::text, 0));

  select i.price_g into v_price
  from public.shop_items i
  where i.id = p_item_id and i.active
  for share;

  if v_price is null then
    raise exception 'shop item unavailable' using errcode = '22023';
  end if;
  v_total := v_price::bigint * p_quantity::bigint;

  select coalesce((select sum(p.amount)::bigint from public.quest_reward_payouts p where p.user_id = v_user_id), 0)
       + coalesce((select sum(g.amount)::bigint from public.guild_gold_grants g where g.user_id = v_user_id), 0)
       - coalesce((select sum(p.price_paid)::bigint from public.shop_purchases p where p.user_id = v_user_id), 0)
    into v_balance;

  if v_balance < v_total then
    return 'insufficient_funds';
  end if;

  insert into public.shop_purchases (user_id, item_id, quantity, price_paid, purchased_at)
  values (v_user_id, p_item_id, p_quantity, v_total, now())
  on conflict (user_id, item_id) do update
    set quantity = public.shop_purchases.quantity + excluded.quantity,
        price_paid = public.shop_purchases.price_paid + excluded.price_paid,
        purchased_at = excluded.purchased_at;

  return 'purchased';
end;
$$;

create or replace function public.join_quest(p_quest_id text)
returns text
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := auth.uid();
  v_max integer;
  v_count integer;
  v_awarded_at timestamptz;
begin
  if v_user_id is null then
    raise exception 'authentication required' using errcode = '28000';
  end if;

  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended(p_quest_id, 0));

  select max_members, awarded_at into v_max, v_awarded_at
  from public.quest_limits
  where quest_id = p_quest_id and active;

  if v_max is null then
    raise exception 'unknown quest' using errcode = '22023';
  end if;
  if v_awarded_at is not null then
    return 'closed';
  end if;
  if exists (
    select 1 from public.quest_participants
    where quest_id = p_quest_id and user_id = v_user_id
  ) then
    return 'already_joined';
  end if;

  select count(*) into v_count
  from public.quest_participants
  where quest_id = p_quest_id;

  if v_count >= v_max then
    return 'full';
  end if;

  insert into public.quest_participants (quest_id, user_id)
  values (p_quest_id, v_user_id);

  return 'joined';
end;
$$;

create or replace function public.award_quest(p_quest_id text)
returns text
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_admin_id uuid := auth.uid();
  v_reward integer;
  v_mode text;
  v_awarded_at timestamptz;
  v_participants bigint;
begin
  if v_admin_id is null or not exists (
    select 1 from public.quest_admins a where a.user_id = v_admin_id
  ) then
    raise exception 'administrator access required' using errcode = '42501';
  end if;

  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended(p_quest_id, 0));

  select reward_amount, reward_mode, awarded_at
    into v_reward, v_mode, v_awarded_at
  from public.quest_limits
  where quest_id = p_quest_id and active
  for update;

  if not found then
    raise exception 'unknown quest' using errcode = '22023';
  end if;
  if v_awarded_at is not null then
    return 'already_awarded';
  end if;

  select count(*) into v_participants
  from public.quest_participants p
  where p.quest_id = p_quest_id;
  if v_participants = 0 then
    return 'no_participants';
  end if;

  if v_mode = 'team_pool' then
    insert into public.quest_reward_payouts (quest_id, user_id, amount, awarded_by)
    select p_quest_id,
           ranked.user_id,
           (v_reward / v_participants)::integer
             + case when ranked.position <= (v_reward % v_participants) then 1 else 0 end,
           v_admin_id
    from (
      select p.user_id,
             row_number() over (order by p.joined_at, p.user_id) as position
      from public.quest_participants p
      where p.quest_id = p_quest_id
    ) ranked
    where (v_reward / v_participants)::integer
             + case when ranked.position <= (v_reward % v_participants) then 1 else 0 end > 0;
  else
    insert into public.quest_reward_payouts (quest_id, user_id, amount, awarded_by)
    select p_quest_id, p.user_id, v_reward, v_admin_id
    from public.quest_participants p
    where p.quest_id = p_quest_id;
  end if;

  update public.quest_limits
  set awarded_at = pg_catalog.now()
  where quest_id = p_quest_id;

  return 'awarded';
end;
$$;

