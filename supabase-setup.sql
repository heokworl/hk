as $$
declare v_admin uuid := auth.uid();
begin
  if v_admin is null or not exists (select 1 from public.quest_admins a where a.user_id = v_admin) then
    raise exception 'administrator access required' using errcode = '42501';
  end if;
  update public.shop_item_uses set restored_at = now(), restored_by = v_admin
  where id = p_use_id and restored_at is null;
  if not found then return 'already_restored'; end if;
  return 'restored';
end;
$$;

