drop function if exists public.get_my_inventory();
create function public.get_my_inventory()
returns table (item_id text, item_name text, description text, acquired_at timestamptz, acquisition_type text, quantity integer)
language sql
security definer
stable
set search_path = ''
as $$
  with acquisitions as (
    select p.item_id, p.quantity, p.purchased_at as acquired_at, '구매'::text as source
    from public.shop_purchases p where p.user_id = auth.uid()
    union all
    select g.item_id, 1, g.granted_at, '관리자 지급'::text
    from public.shop_item_grants g where g.user_id = auth.uid()
  ), totals as (
    select a.item_id, sum(a.quantity)::integer as acquired_quantity, max(a.acquired_at) as acquired_at,
           case when bool_or(a.source = '구매') and bool_or(a.source = '관리자 지급') then '구매·관리자 지급'::text
                when bool_or(a.source = '관리자 지급') then '관리자 지급'::text
                else '구매'::text end as acquisition_type
    from acquisitions a group by a.item_id
  ), active_uses as (
    select u.item_id, count(*)::integer as used_quantity
    from public.shop_item_uses u
    where u.user_id = auth.uid() and u.restored_at is null
    group by u.item_id
  )
  select t.item_id, i.name, i.description, t.acquired_at, t.acquisition_type,
         greatest(t.acquired_quantity - coalesce(u.used_quantity, 0), 0)::integer
  from totals t join public.shop_items i on i.id = t.item_id
  left join active_uses u on u.item_id = t.item_id
  where t.acquired_quantity - coalesce(u.used_quantity, 0) > 0
  order by t.acquired_at desc, i.name;
$$;

